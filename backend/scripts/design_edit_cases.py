"""Write tests/fixtures/design_edit_cases.json from pipeline/design_edits.py (run in the api
container:
``python -c "import runpy; runpy.run_path('scripts/design_edit_cases.py', run_name='__main__')"``). Python's tests check the code still gives
these numbers; the editor's (frontend lib/designEdits.test.ts) check it gives the same."""

from __future__ import annotations

import json
from pathlib import Path

import numpy as np

from app.pipeline import design_edits as E

QUAD = [[200, 200], [600, 200], [600, 500], [200, 500]]
PERSPECTIVE = [[180, 210], [620, 190], [640, 520], [170, 500]]

POINTS = [
    ("no adjustment: the automatic fit", QUAD, [800, 400], 1.0, None),
    ("moved right and down", QUAD, [800, 400], 1.0, {"dx": 0.1, "dy": 0.05}),
    ("scaled down, proportions kept", QUAD, [300, 600], 1.0, {"scale": 0.7}),
    ("stretched wider only", QUAD, [300, 600], 0.9, {"sx": 1.4}),
    ("turned 15 degrees", QUAD, [800, 600], 1.0, {"angle": 15}),
    ("free corners", QUAD, [800, 600], 1.0, {"corners": [[0.02, 0.0], [-0.03, 0.01], [0.0, -0.04], [0.01, 0.02]]}),
    ("everything, on a perspective area", PERSPECTIVE, [640, 480], 0.95,
     {"dx": -0.04, "dy": 0.03, "scale": 1.2, "sx": 0.9, "sy": 1.1, "angle": -8,
      "corners": [[0.01, 0.0], [0.0, 0.0], [0.0, 0.02], [-0.01, 0.0]]}),
]


def design(w: int = 14, h: int = 10) -> np.ndarray:
    """A small design: a dark letter shape with soft edges on a light patch, transparent around."""
    rgba = np.zeros((h, w, 4), np.uint8)
    rgba[1:9, 1:13, :3] = (240, 236, 230)
    rgba[1:9, 1:13, 3] = 255
    rgba[3:7, 3:6, :3] = (20, 20, 24)
    rgba[3:7, 8:11, :3] = (22, 21, 25)
    rgba[2, 3:6, 3] = 128  # a soft edge
    rgba[0, 0] = (90, 90, 90, 40)
    return rgba


REGIONS = [
    ("a rectangle", {"kind": "rect", "points": [[0.2, 0.25], [0.45, 0.75]], "colour": "#ffffff"}),
    ("a lasso", {"kind": "lasso", "points": [[0.5, 0.2], [0.85, 0.3], [0.8, 0.8], [0.55, 0.7]], "colour": "#ff0000"}),
    ("a wand click on the dark left letter", {"kind": "wand", "seed": [0.3, 0.5], "tolerance": 10, "colour": "#ffffff"}),
    ("a wide wand click on the light patch", {"kind": "wand", "seed": [0.08, 0.15], "tolerance": 20, "colour": "#000000"}),
    ("a wand click on padding selects nothing", {"kind": "wand", "seed": [0.99, 0.99], "tolerance": 50, "colour": "#000000"}),
]

LOOKS = [
    ("neutral", None),
    ("brighter", {"brightness": 0.1}),
    ("more contrast, less opaque", {"contrast": 0.2, "opacity": 0.6}),
    ("darker, less contrast", {"brightness": -0.2, "contrast": -0.25}),
]

COMPOSE = [
    ("moved and scaled on top of another's own adjustment",
     {"dx": 0.0, "dy": 0.0}, {"dx": 0.05, "scale": 1.2}, {"dx": -0.1, "scale": 0.8, "angle": 10}),
    ("a turn past 180 wraps", None, {"angle": 30}, {"angle": 170}),
    ("the look adds", {"opacity": 0.9}, {"opacity": 0.7, "brightness": 0.1}, {"opacity": 1.0}),
    ("back to neutral is nothing to store", {"dx": 0.1}, None, {"dx": 0.1}),
]


def main() -> None:
    out = {
        "_note": "Generated by scripts/design_edit_cases.py from pipeline/design_edits.py; lib/designEdits.ts must give the same.",
        "points": [], "looks": [], "regions": [], "compose": [],
    }
    for name, quad, size_, size, adj in POINTS:
        pts = [tuple(p) for p in quad]
        out["points"].append({
            "name": name, "quad": quad, "design": size_, "size": size, "adjust": adj,
            "unit": [[round(u, 6), round(v, 6)] for u, v in E.unit_points(pts, tuple(size_), size, adj)],
            "photo": [[round(x, 4), round(y, 4)] for x, y in E.photo_points(pts, tuple(size_), size, adj)],
        })
    d = design()
    for name, adj in LOOKS:
        looked = E.look_rgba(d, adj)
        out["looks"].append({"name": name, "adjust": adj, "pixels": d.reshape(-1).tolist(), "out": looked.reshape(-1).tolist()})
    h, w = d.shape[:2]
    for name, region in REGIONS:
        mask = E.region_mask(d, region)
        out["regions"].append({
            "name": name, "region": region, "width": w, "height": h, "pixels": d.reshape(-1).tolist(),
            "mask": [int(i) for i in np.flatnonzero(mask)],
            "recoloured": E.recolour(d, [region]).reshape(-1).tolist(),
        })
    for name, before, after, target in COMPOSE:
        out["compose"].append({"name": name, "before": before, "after": after, "target": target,
                               "result": E.compose(target, E.delta(before, after))})
    path = Path(__file__).resolve().parent.parent / "tests" / "fixtures" / "design_edit_cases.json"
    path.write_text(json.dumps(out, indent=1) + "\n", encoding="utf-8")
    print(f"wrote {path}")


if __name__ == "__main__":
    main()
